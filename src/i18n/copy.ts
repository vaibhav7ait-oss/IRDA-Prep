export type CopyKey = keyof typeof COPY.en;

export function createTranslator(lang: Language) {
  return (key: CopyKey, values: Record<string, string | number> = {}): string => {
    const template = COPY[lang]?.[key] || COPY.en[key] || key;
    return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
  };
}

export function getSubjectName(lang: Language, category: string): string {
  return SUBJECTS[lang]?.[category] || category;
}
